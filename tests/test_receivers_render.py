"""The [[receiver]] list reaches coordination.env."""
from __future__ import annotations

import importlib.util
import os
import types
from pathlib import Path
from unittest import mock

import pytest

import sigmond.site_profile as sp
from sigmond.coordination import Coordination, render_env
from sigmond.receivers import Receiver

B1A = 'ac0g-b1-a-status.local'
B1B = 'ac0g-b1-b-status.local'
TWO = [Receiver(reporter_id='AC0G/B1A', radiod=B1A),
       Receiver(reporter_id='AC0G/B1B', radiod=B1B)]
PROFILE = ('[[receiver]]\nreporter_id = "AC0G/B1A"\n'
           f'radiod = "{B1A}"\n')


def _smd():
    spec = importlib.util.spec_from_loader('smd_mod_rr', loader=None)
    smd = importlib.util.module_from_spec(spec)
    smd.__dict__['__file__'] = 'bin/smd'
    src = Path(__file__).resolve().parent.parent / 'bin' / 'smd'
    with mock.patch.dict(os.environ, {'SIGMOND_NO_VENV_REEXEC': '1'}):
        exec(compile(src.read_text(), str(src), 'exec'), smd.__dict__)
    return smd


def test_no_receivers_adds_no_lines():
    c = Coordination()
    assert 'RECEIVER' not in render_env(c, receivers=[])
    assert render_env(c, receivers=[]) == (
        '# Generated by sigmond — do not edit.\n'
        '# Source: /etc/sigmond/coordination.toml\n')


def test_two_receivers_publish_count_reporter_and_radiod():
    lines = render_env(Coordination(), receivers=TWO).splitlines()
    assert 'RECEIVER_COUNT=2' in lines
    assert 'RECEIVER_1_REPORTER=AC0G/B1A' in lines
    assert f'RECEIVER_1_RADIOD={B1A}' in lines
    assert 'RECEIVER_2_REPORTER=AC0G/B1B' in lines
    assert f'RECEIVER_2_RADIOD={B1B}' in lines


def test_a_bad_profile_warns_and_adds_no_lines(tmp_path, capsys):
    p = tmp_path / 'site-profile.toml'
    p.write_text('[[receiver]\nbroken')
    with mock.patch.object(sp, 'SITE_PROFILE_PATH', p):
        out = render_env(Coordination())
    assert 'RECEIVER' not in out
    assert capsys.readouterr().err.count('receiver') >= 1


def test_every_coordination_env_writer_carries_the_receivers(tmp_path):
    smd = _smd()
    etc = tmp_path / 'etc'
    prof = tmp_path / 'site-profile.toml'
    prof.write_text(PROFILE)
    coord = etc / 'sigmond' / 'coordination.toml'
    with mock.patch.object(sp, 'SITE_PROFILE_PATH', prof):
        rc = smd._sources_bind(B1A, 'AC0G/B1A', ['psk-recorder'],
                               host='ac0g-b1', etc_root=etc,
                               coord_path=coord, inventory_rows=[])
    assert rc == 0
    env = (etc / 'sigmond' / 'coordination.env').read_text()
    assert 'RECEIVER_1_REPORTER=AC0G/B1A' in env
    assert f'RECEIVER_1_RADIOD={B1A}' in env


def _render(tmp_path, body, capsys):
    import sigmond.commands.config as cfg
    prof = tmp_path / 'site-profile.toml'
    prof.write_text(body)
    coord = tmp_path / 'coordination.toml'
    env = tmp_path / 'coordination.env'
    with mock.patch.object(sp, 'SITE_PROFILE_PATH', prof), \
            mock.patch.object(cfg, 'SITE_PROFILE_PATH', prof), \
            mock.patch.object(cfg, 'COORDINATION_PATH', coord), \
            mock.patch.object(cfg, 'COORDINATION_ENV', env):
        rc = cfg.cmd_config_render(types.SimpleNamespace())
    return rc, env, capsys.readouterr()


def test_a_profile_with_receivers_and_no_station_renders(tmp_path, capsys):
    rc, env, cap = _render(tmp_path, PROFILE, capsys)
    assert rc == 0
    assert 'RECEIVER_1_REPORTER=AC0G/B1A' in env.read_text()
    assert 'callsign' not in cap.out + cap.err
    assert 'no [station] table' in cap.out + cap.err


def test_render_fails_on_a_bad_receiver_list(tmp_path, capsys):
    bad = PROFILE + '\n[[receiver]]\nreporter_id = "AC0G/B1B"\n'  # no radiod
    rc, env, cap = _render(tmp_path, bad, capsys)
    assert rc == 1
    assert 'names no radiod' in cap.out + cap.err
    assert not env.exists()


def test_a_receiver_the_guard_drops_is_not_counted(capsys):
    """R17.5: RECEIVER_COUNT counts only the pairs that reach the file."""
    rs = [Receiver(reporter_id='AC0G/B1A', radiod='bad"name.local'),
          Receiver(reporter_id='AC0G/B1B', radiod=B1B)]
    env = render_env(Coordination(), passthrough_lookup=lambda t: [],
                     receivers=rs)
    lines = [ln for ln in env.splitlines() if ln.startswith('RECEIVER_')]
    assert lines == ['RECEIVER_COUNT=1', 'RECEIVER_1_REPORTER=AC0G/B1B',
                     f'RECEIVER_1_RADIOD={B1B}']
    assert 'AC0G/B1A' in capsys.readouterr().err
    only_bad = render_env(Coordination(), passthrough_lookup=lambda t: [],
                          receivers=rs[:1])
    assert 'RECEIVER_' not in only_bad
