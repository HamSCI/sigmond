"""sigmond.radiod_rename: the pure planner for `smd admin radiod rename`."""
import json
from pathlib import Path

import pytest

from sigmond.radiod_rename import (Edit, Move, describe_plan, plan,
                                   rename_coord, rewrite_token,
                                   set_description, set_status, status_of,
                                   valid_id)

COMPONENTS = ["hf-timestd", "psk-recorder", "wspr-recorder",
              "meteor-scatter", "mag-recorder", "ka9q-web"]


def _conf(instance: str, status: str, description: str, serial: str) -> str:
    return f"""# /etc/radio/radiod@{instance}.conf
#
# Generated by `smd config init radiod` (CONTRACT-v0.5 §14).
# This is a minimal config — channel definitions for clients
# (WSPR, FT8, FT4, HFDL, time standards, etc.) are normally
# dropped into:
#
#     /etc/radio/radiod@{instance}.conf.d/<NN>-<client>.conf
#
# and read in lexical order.

[global]
hardware  = rx888              # which front-end driver to load
status    = {status}      # mDNS name for status + control multicast
samprate  = 12000
mode      = usb
ttl       = 0
fft-threads = 1
affinity  = false              # let systemd CPUAffinity= confine us
iface     = lo

[rx888]
device      = "rx888"          # required so this isn't parsed as a demod
description = "{description}" # callsign + antenna; surfaces in status
serial      = "{serial}"
samprate    = 129600000
"""


COORD = """\
# /etc/sigmond/coordination.toml — written by smd config init

[host]
call = "AI6VN"
grid = "CM87"

[radiod."AI6VN-status.local"]
host       = "localhost"
radio_conf = "/etc/radio/radiod@AI6VN.conf"
sdr_serial  = "0009002807411037"

# second card, registered 2026-10-30
[radiod."omni"]
host       = "localhost"
status_dns = "omni-status.local"
radio_conf = "/etc/radio/radiod@omni.conf"
sdr_serial  = "0009061C028B352B"
"""

CLIENT_TOML = '''\
[radiod]
status = "AI6VN-status.local"
'''


def ai6vn_pm(tmp_path: Path) -> Path:
    """AI6VN-PM's radiod-related files as of 2026-10-31, under tmp_path."""
    root = tmp_path

    def w(rel: str, text: str) -> None:
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)

    w("etc/radio/radiod@AI6VN.conf",
      _conf("AI6VN", "AI6VN-status.local", "AI6VN RX-888 Mk2",
            "0009002807411037"))
    w("etc/radio/radiod@omni.conf",
      _conf("omni", "omni-status.local", "AI6VN TCI-530 Omni",
            "0009061C028B352B"))
    (root / "etc/radio/radiod@AI6VN.conf.d").mkdir(parents=True)
    w("etc/sigmond/coordination.toml", COORD)
    w("etc/sigmond/coordination.env",
      "# generated by smd\nRADIOD_AI6VN_STATUS_LOCAL_STATUS=AI6VN-status.local\n")
    w("etc/systemd/system/ka9q-web.service",
      "[Unit]\nDescription=ka9q-web\n\n[Service]\n"
      "ExecStart=/usr/local/sbin/ka9q-web -m AI6VN-status.local -p 8081\n")
    w("etc/systemd/system/radiod@AI6VN.service.d/smd-cpu-affinity.conf",
      "[Service]\nCPUAffinity=0 1\n")
    w("etc/hf-timestd/timestd-config.toml",
      '[ka9q]\nstatus = "AI6VN-status.local"\n')
    for comp, names in (("psk-recorder", ("AI6VN.toml", "psk-recorder-config.toml")),
                        ("wspr-recorder", ("AI6VN.toml", "config.toml")),
                        ("meteor-scatter", ("AI6VN.toml", "meteor-scatter-config.toml"))):
        for n in names:
            w(f"etc/{comp}/{n}", CLIENT_TOML)
    w("etc/hs-uploader/pipelines.toml",
      '[[pipeline]]\nname = "psk-pskreporter"\n'
      'decoding_software = "psk-recorder/0.1 (radiod=AI6VN-status.local)"\n\n'
      '[[pipeline]]\nname = "psk-wsprdaemon"\n'
      'decoding_software = "psk-recorder/0.1 (radiod=AI6VN-status.local)"\n')
    w("etc/sigmond/clients/psk-recorder@AI6VN.sources.toml", "selections = []\n")
    return root


def _tree(root: Path) -> dict:
    return {p.relative_to(root).as_posix(): p.read_bytes()
            for p in sorted(root.rglob("*")) if p.is_file()}


def _apply(p, root: Path) -> None:
    """What the command layer does: moves first, then edits (new paths)."""
    for m in p.moves:
        m.src.rename(m.dst)
    for e in p.edits:
        assert e.path.read_text() == e.before
        e.path.write_text(e.after)


# ---------- pure text helpers ----------

def test_valid_id():
    assert valid_id("se") and valid_id("AI6VN") and not valid_id("se/1") and not valid_id("")


def test_rewrite_token_is_whole_token():
    assert rewrite_token("x base-status.local y", "se-status.local", "z") == "x base-status.local y"
    assert (rewrite_token("A=AI6VN-status.local", "AI6VN-status.local", "omni-status.local")
            == "A=omni-status.local")
    assert (rewrite_token('"radiod:AI6VN-status.local" AI6VN-status.locale',
                          "AI6VN-status.local", "se-status.local")
            == '"radiod:se-status.local" AI6VN-status.locale')
    assert rewrite_token("-m AI6VN-status.local\n", "AI6VN-status.local", "o") == "-m o\n"


def test_set_status_keeps_comment_and_inserts_when_absent():
    text = _conf("AI6VN", "AI6VN-status.local", "d", "1")
    assert status_of(text) == "AI6VN-status.local"
    out = set_status(text, "omni-status.local")
    assert status_of(out) == "omni-status.local"
    line = next(l for l in out.splitlines() if l.startswith("status"))
    assert line.startswith("status    = omni-status.local ")
    assert line.endswith("# mDNS name for status + control multicast")
    # only that line changed
    assert [a for a, b in zip(text.splitlines(), out.splitlines()) if a != b] == [
        next(l for l in text.splitlines() if l.startswith("status"))]

    bare = "[global]\nhardware = rx888\n\n[rx888]\nstatus = notme\n"
    assert status_of(bare) == ""
    ins = set_status(bare, "se-status.local")
    assert ins == "[global]\nstatus    = se-status.local\nhardware = rx888\n\n[rx888]\nstatus = notme\n"
    assert status_of(ins) == "se-status.local"


def test_set_description_rewrites_or_inserts_and_refuses_without_section():
    text = _conf("AI6VN", "AI6VN-status.local", "AI6VN RX-888 Mk2", "1")
    out = set_description(text, "TCI-530 Omni")
    assert 'description = "TCI-530 Omni" # callsign + antenna; surfaces in status' in out
    assert "AI6VN RX-888 Mk2" not in out
    assert len(out.splitlines()) == len(text.splitlines())

    nodesc = "[global]\nhardware = rx888\n\n[rx888]\ndevice = \"rx888\"\nserial = \"X\"\n\n[40m]\nfreq = 7m\n"
    ins = set_description(nodesc, "se")
    assert ins == ("[global]\nhardware = rx888\n\n[rx888]\ndevice = \"rx888\"\n"
                   "serial = \"X\"\ndescription = \"se\"\n\n[40m]\nfreq = 7m\n")

    with pytest.raises(ValueError):
        set_description("[global]\nhardware = rx888\n", "x")
    with pytest.raises(ValueError):
        set_description("[global]\nstatus = a\n", "x")


def test_rename_coord_status_keyed_table_stays_status_keyed():
    text = COORD + ('\n[[clients.psk-recorder]]\ninstance = "AI6VN"\n'
                    'radiod_id = "AI6VN-status.local"\n\n'
                    '[timing_authority.per_radiod."AI6VN-status.local"]\n'
                    'source = "hf-timestd"\n')
    out = rename_coord(text, "AI6VN", "omni", "AI6VN-status.local", "omni-status.local")
    assert '[radiod."omni-status.local"]' in out
    assert '[radiod."AI6VN-status.local"]' not in out
    assert 'radio_conf = "/etc/radio/radiod@omni.conf"' in out
    assert 'radiod_id = "omni-status.local"' in out
    assert '[timing_authority.per_radiod."omni-status.local"]' in out
    assert 'instance = "AI6VN"' in out          # reporter id untouched
    assert 'call = "AI6VN"' in out
    # no status_dns added to the status-keyed table
    blk = out.split('[radiod."omni-status.local"]')[1].split("[")[0]
    assert "status_dns" not in blk
    # everything outside the edited lines is byte-identical
    changed = [(a, b) for a, b in zip(text.splitlines(True), out.splitlines(True)) if a != b]
    assert len(text.splitlines()) == len(out.splitlines())
    assert len(changed) == 4


def test_rename_coord_id_keyed_table_gets_new_status_dns():
    text = COORD + ('\n[[clients.wspr-recorder]]\nradiod_id = "omni"\n\n'
                    '[timing_authority.per_radiod.omni]\nsource = "x"\n')
    out = rename_coord(text, "omni", "se", "omni-status.local", "se-status.local")
    assert '[radiod."se"]' in out and '[radiod."omni"]' not in out
    blk = out.split('[radiod."se"]')[1]
    assert blk.splitlines()[2] == 'status_dns = "se-status.local"'
    assert 'radio_conf = "/etc/radio/radiod@se.conf"' in out
    assert 'radiod_id = "se"' in out
    assert "[timing_authority.per_radiod.se]" in out
    # the AI6VN table and the comments are untouched
    assert out.startswith(COORD.split('[radiod."omni"]')[0])

    # an id-keyed table with no status_dns gets one right after its header
    bare = '[radiod.omni]\nhost = "localhost"\n'
    assert (rename_coord(bare, "omni", "se", "omni-status.local", "se-status.local")
            == '[radiod."se"]\nstatus_dns = "se-status.local"\nhost = "localhost"\n')


