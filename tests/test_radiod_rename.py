def test_plan_omni_to_se_on_ai6vn_pm(tmp_path):
    root = ai6vn_pm(tmp_path)
    before = _tree(root)
    p = plan("omni", "se", root=root, components=COMPONENTS)
    assert not p.refused, p.refusals
    assert (p.old, p.new, p.old_status, p.new_status) == (
        "omni", "se", "omni-status.local", "se-status.local")
    assert p.moves == [Move(root / "etc/radio/radiod@omni.conf",
                            root / "etc/radio/radiod@se.conf")]
    assert [e.path for e in p.edits] == [root / "etc/radio/radiod@se.conf",
                                         root / "etc/sigmond/coordination.toml"]
    conf = p.edits[0].after
    assert status_of(conf) == "se-status.local"
    assert "# /etc/radio/radiod@se.conf\n" in conf
    assert "#     /etc/radio/radiod@se.conf.d/<NN>-<client>.conf\n" in conf
    assert 'description = "AI6VN TCI-530 Omni"' in conf    # no --description
    assert '[radiod."se"]' in p.edits[1].after
    assert p.affected_components == []
    assert p.not_edited == []
    assert _tree(root) == before                 # pure: nothing written


def test_plan_ai6vn_to_omni_after_first_rename(tmp_path):
    root = ai6vn_pm(tmp_path)
    _apply(plan("omni", "se", root=root, components=COMPONENTS), root)
    before = _tree(root)

    p = plan("AI6VN", "omni", description="TCI-530 Omni", root=root,
             components=COMPONENTS)
    assert not p.refused, p.refusals
    assert p.moves == [
        Move(root / "etc/radio/radiod@AI6VN.conf", root / "etc/radio/radiod@omni.conf"),
        Move(root / "etc/radio/radiod@AI6VN.conf.d", root / "etc/radio/radiod@omni.conf.d"),
        Move(root / "etc/systemd/system/radiod@AI6VN.service.d",
             root / "etc/systemd/system/radiod@omni.service.d"),
    ]
    rel = sorted(e.path.relative_to(root).as_posix() for e in p.edits)
    assert rel == sorted([
        "etc/radio/radiod@omni.conf",
        "etc/sigmond/coordination.toml",
        "etc/sigmond/coordination.env",
        "etc/systemd/system/ka9q-web.service",
        "etc/hf-timestd/timestd-config.toml",
        "etc/psk-recorder/AI6VN.toml",
        "etc/psk-recorder/psk-recorder-config.toml",
        "etc/wspr-recorder/AI6VN.toml",
        "etc/wspr-recorder/config.toml",
        "etc/meteor-scatter/AI6VN.toml",
        "etc/meteor-scatter/meteor-scatter-config.toml",
        "etc/hs-uploader/pipelines.toml",
    ])
    by = {e.path.relative_to(root).as_posix(): e for e in p.edits}
    conf = by["etc/radio/radiod@omni.conf"].after
    assert status_of(conf) == "omni-status.local"
    assert "# /etc/radio/radiod@omni.conf\n" in conf
    assert "#     /etc/radio/radiod@omni.conf.d/<NN>-<client>.conf\n" in conf
    assert 'description = "TCI-530 Omni" # callsign + antenna' in conf
    assert 'serial      = "0009002807411037"' in conf
    assert "AI6VN-status" not in conf and "radiod@AI6VN" not in conf
    coord = by["etc/sigmond/coordination.toml"].after
    assert '[radiod."omni-status.local"]' in coord and '[radiod."se"]' in coord
    assert 'radio_conf = "/etc/radio/radiod@omni.conf"' in coord
    assert by["etc/sigmond/coordination.env"].after.endswith(
        "RADIOD_AI6VN_STATUS_LOCAL_STATUS=omni-status.local\n")
    assert "-m omni-status.local -p 8081" in by["etc/systemd/system/ka9q-web.service"].after
    assert by["etc/psk-recorder/AI6VN.toml"].after == CLIENT_TOML.replace(
        "AI6VN-status.local", "omni-status.local")
    assert by["etc/hs-uploader/pipelines.toml"].after.count("(radiod=omni-status.local)") == 2
    for e in p.edits:
        assert e.before != e.after
    assert p.affected_components == ["hf-timestd", "meteor-scatter",
                                     "psk-recorder", "wspr-recorder"]
    assert "/var/lib/psk-recorder/AI6VN-status.local/" in p.history
    assert _tree(root) == before

    _apply(p, root)
    for f in root.rglob("*"):
        if f.is_file():
            assert "AI6VN-status.local" not in f.read_text(), f


def test_plan_refusals(tmp_path):
    root = ai6vn_pm(tmp_path)
    before = _tree(root)

    def only(p):
        assert p.refused and p.edits == [] and p.moves == []
        return p.refusals

    r = only(plan("AI6VN", "omni", root=root, components=COMPONENTS))
    assert any("radiod@omni.conf already exists" in s for s in r)
    assert any('coordination table [radiod."omni"]' in s for s in r)

    r = only(plan("AI6VN", "se/1", root=root, components=COMPONENTS))
    assert any("'se/1' is not a valid radiod id" in s for s in r)

    hold = {"0009002807411037": {"serial": "0009002807411037",
                                 "radiod_unit": "radiod@AI6VN.service"}}
    r = only(plan("AI6VN", "se", root=root, components=COMPONENTS, hold=hold))
    assert r == ["a manual RX888 hold names radiod@AI6VN.service; clear it first: "
                 "sigmond-sdr-recover --on"]

    r = only(plan("nope", "se", root=root, components=COMPONENTS))
    assert any("no /etc/radio/radiod@nope.conf" in s for s in r)

    (root / "etc/radio/radiod@gen.conf").write_text("[global]\nhardware = sig_gen\n")
    r = only(plan("gen", "se", root=root, components=COMPONENTS))
    assert any("signal generator" in s for s in r)

    (root / "etc/systemd/system/radiod@se.service.d").mkdir()
    r = only(plan("AI6VN", "se", root=root, components=COMPONENTS))
    assert any("radiod@se.service.d already exists" in s for s in r)

    # every refusal collected, in the documented order
    (root / "etc/radio/radiod@x.conf").write_text("[global]\nhardware = sig_gen\n")
    r = only(plan("bootstrap-fw1", "x", root=root, components=COMPONENTS))
    assert len(r) == 3 and "no /etc/radio/radiod@bootstrap-fw1.conf" in r[0]
    assert "radiod@x.conf already exists" in r[1]
    assert "bootstrap" in r[2]
    for s in r:
        assert s.endswith(".") or ":" in s
    (root / "etc/radio/radiod@x.conf").unlink()
    (root / "etc/systemd/system/radiod@se.service.d").rmdir()
    (root / "etc/radio/radiod@gen.conf").unlink()
    assert _tree(root) == before


def test_plan_reports_history_and_not_edited(tmp_path):
    root = ai6vn_pm(tmp_path)
    (root / "etc/foo").mkdir()
    (root / "etc/foo/bar.conf").write_text("upstream = AI6VN-status.local\n")
    (root / "var/lib/sigmond").mkdir(parents=True)
    (root / "var/lib/sigmond/sdr-labels.toml").write_text(
        '["ka9q_fe:AI6VN-status.local:0"]\nlabel = "Omni"\n')
    (root / "var/lib/sigmond/sdr-hold.json").write_text(json.dumps({}))
    (root / "var/lib/sigmond/notes.txt").write_text("AI6VN-status.local\n")
    (root / "etc/foo/link").symlink_to("/etc/passwd")

    p = plan("AI6VN", "se", root=root, components=COMPONENTS)
    assert not p.refused
    assert p.not_edited == [root / "etc/foo/bar.conf",
                            root / "var/lib/sigmond/notes.txt"]
    labels = next(e for e in p.edits
                  if e.path == root / "var/lib/sigmond/sdr-labels.toml")
    assert '"ka9q_fe:se-status.local:0"' in labels.after
    assert p.history == [
        "/var/lib/psk-recorder/AI6VN-status.local/",
        "/var/log/psk-recorder/AI6VN-status.local-*.log",
        "/var/log/meteor-scatter/AI6VN-status.local-*.log",
        "/dev/shm/wspr-recorder/AI6VN-status.local/",
    ]


def test_plan_clients_bound_in_coordination_are_affected(tmp_path):
    root = ai6vn_pm(tmp_path)
    coord = root / "etc/sigmond/coordination.toml"
    coord.write_text(coord.read_text() + '\n[[clients.hfdl-recorder]]\n'
                     'radiod_id = "AI6VN-status.local"\n')
    p = plan("AI6VN", "se", root=root, components=COMPONENTS)
    assert "hfdl-recorder" in p.affected_components
    assert p.affected_components == sorted(set(p.affected_components))


def test_describe_plan(tmp_path):
    root = ai6vn_pm(tmp_path)
    p = describe_plan("AI6VN", "TCI-530 Omni", root=root)
    assert not p.refused and p.moves == []
    assert len(p.edits) == 1
    e = p.edits[0]
    assert e.path == root / "etc/radio/radiod@AI6VN.conf"
    changed = [b for a, b in zip(e.before.splitlines(), e.after.splitlines()) if a != b]
    assert changed == ['description = "TCI-530 Omni" # callsign + antenna; surfaces in status']

    p = describe_plan("nope", "x", root=root)
    assert p.refused and p.edits == []
    assert "no /etc/radio/radiod@nope.conf" in p.refusals[0]

    (root / "etc/radio/radiod@bare.conf").write_text("[global]\nstatus = b\n")
    p = describe_plan("bare", "x", root=root)
    assert p.refused and p.edits == []
    assert "hardware section" in p.refusals[0]
