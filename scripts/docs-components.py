#!/usr/bin/env python3
"""Write the component table in docs/COMPONENTS.md from the catalog and the
release list, so the suite's top-level view cannot drift from what sigmond
installs.

    python3 scripts/docs-components.py            # print the table
    python3 scripts/docs-components.py --check    # exit 1 if the page differs
    python3 scripts/docs-components.py --write    # rewrite the table in place

Sources, in order: etc/catalog.toml (kind, description, repo, the dasi2
profile's groups), release/components.toml (the pinned commit),
lib/sigmond/release_list.py (the rows and their extra URLs), and bin/smd's
`_<NAME>_REPO` constants for the natively built sources.  A component no
source describes gets its line from DESCRIBED below.
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PAGE = REPO / "docs" / "COMPONENTS.md"
BEGIN = "<!-- BEGIN components: generated by scripts/docs-components.py; do not edit by hand -->"
END = "<!-- END components -->"

# Components with no catalog entry: what they are, in one line.
DESCRIBED = {
    "ka9q-python": "Python library for ka9q-radio control and monitoring; every RF client receives through it (on PyPI)",
    "ft8_lib": "FT8/FT4 decoder library behind psk-recorder's `decode_ft8`, its low-CPU option (pinned by psk-recorder)",
    "onion": "HTTP library that ka9q-web links (built natively by sigmond)",
    "ubersdr_wsprd": "UberSDR's `wsprd` and `jt9`: the station's WSPR, FT8/FT4 and MSK144 decoders (built natively, checked against WSJT-X)",
    "wsjtx": "WSJT-X's `wsprd` and `jt9`: the fallback decoders and the parity reference (built natively)",
    "sigmond-proxmox": "Build pipeline for the Proxmox USB image: a Proxmox host with the station in a VM",
}
# Repositories not in the catalog or release_list.EXTRA_URLS.
OWNED_ELSEWHERE = {"ft8_lib": "https://github.com/ka9q/ft8_lib"}

GROUPS = ("core client", "additional client", "station infrastructure",
          "radio", "library", "native build", "image", "other")


def _repo_url(raw: str) -> str:
    return re.sub(r"\.git$", "", raw.strip().rstrip("/"))


def rows() -> list[dict]:
    catalog = tomllib.loads((REPO / "etc" / "catalog.toml").read_text())
    clients = catalog.get("client", {})
    dasi2 = catalog.get("profile", {}).get("dasi2", {})
    release = tomllib.loads((REPO / "release" / "components.toml").read_text())
    pinned = release.get("components", {})
    version = release.get("version", "")

    sys.path.insert(0, str(REPO / "lib"))
    from sigmond import release_list  # noqa: E402

    smd = (REPO / "bin" / "smd").read_text()
    native_repo = {name: _repo_url(m.group(1)) for name, const in
                   (("onion", "_ONION_REPO"), ("wsjtx", "_WSJTX_REPO"),
                    ("ubersdr_wsprd", "_UBERSDR_REPO"))
                   for m in [re.search(rf"^{const}\s*=\s*'([^']+)'", smd, re.M)] if m}

    names = sorted(set(release_list.ROWS) | set(clients))
    out = []
    for name in names:
        entry = clients.get(name, {})
        kind = entry.get("kind", "")
        if name in dasi2.get("clients", []):
            group = "core client"
        elif name in dasi2.get("optional", []):
            group = "additional client"
        elif name in dasi2.get("local_radiod_infra", []) or kind == "infra":
            group = "station infrastructure"
        elif name == "ka9q-radio":
            group = "radio"
        elif kind == "library" or name == "ka9q-python":
            group = "library"
        elif name in release_list.NATIVE_CONSTANTS or name == "ft8_lib":
            group = "native build"
        elif name == release_list.PROXMOX_ROW:
            group = "image"
        else:
            group = "other"
        # The image row's name is its repository's current name; release_list
        # keeps the pre-rename URL on purpose, and readers should see the new one.
        if name == release_list.PROXMOX_ROW:
            url = f"https://github.com/HamSCI/{name}"
        else:
            url = ""
        url = (url or entry.get("repo") or release_list.EXTRA_URLS.get(name)
               or native_repo.get(name) or OWNED_ELSEWHERE.get(name) or "")
        out.append({
            "name": name,
            "group": group,
            "what": " ".join((entry.get("description") or DESCRIBED.get(name, "")).split()),
            "url": _repo_url(url) if url else "",
            "pin": pinned.get(name, ""),
            "version": version,
        })
    out.sort(key=lambda r: (GROUPS.index(r["group"]), r["name"]))
    return out


def table() -> str:
    rs = rows()
    version = rs[0]["version"] if rs else ""
    lines = [BEGIN, "",
             f"| Component | Group | What it does | Repository | In {version} |",
             "|---|---|---|---|---|"]
    for r in rs:
        # The repository only, for now: a docs/INDEX.md link waits until every
        # repo carries one (ledger docs-organization, step 3).
        where = (f"[{r['url'].split('github.com/')[-1]}]({r['url']})"
                 if r["url"] else "")
        pin = f"`{r['pin'][:8]}`" if r["pin"] else "not yet released"
        what = r["what"].replace("|", "\\|")
        lines.append(f"| **{r['name']}** | {r['group']} | {what} | {where} | {pin} |")
    lines += ["", END]
    return "\n".join(lines) + "\n"


def _replace(text: str, new: str) -> str:
    i, j = text.index(BEGIN), text.index(END) + len(END) + 1
    return text[:i] + new + text[j:]


def main(argv: list[str]) -> int:
    new = table()
    if "--write" in argv:
        PAGE.write_text(_replace(PAGE.read_text(), new))
        return 0
    if "--check" in argv:
        if _replace(PAGE.read_text(), new) != PAGE.read_text():
            print("docs/COMPONENTS.md is out of date: run scripts/docs-components.py --write")
            return 1
        return 0
    sys.stdout.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
